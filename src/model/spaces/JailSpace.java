package model.spaces;

/**
 * Represent the jail space.
 * 
 * This class represents the jail space on the Monopoly
 * board where a player is sent when they go to jail. It 
 * has Space as its superclass.
 * 
 * @author Tyler Ohme
 */
public class JailSpace extends Space {
	/**
	 * Builds a new JailSpace object.
	 * 
	 * @param name the name of this space
	 * Author: Tyler Ohme
	 */
	public JailSpace(String name) {
		super(name);
	}
}
